// Timer callbacks----------------------------------------
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim){
  if(htim == &htim6){
    tap_tempo_update((bool)HAL_GPIO_ReadPin(TAP_IN_GPIO_Port, TAP_IN_Pin));
    globalSeconds += secsIncrement;
  } else if (htim == &htim21){
    readPotADCs();
    // if the speed control moved, don't bother checking on the tap tempo
    if(speedKnobMoved){
      inTapMode = false;
      speedKnobMoved = false;
    } else if (tap_tempo_was_tapped_within(0.01f)){
      inTapMode = true;
      lfo_update_period(&lfo, tap_tempo_current_period());
    }

  }
}
